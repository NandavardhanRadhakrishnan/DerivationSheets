// Preserve copies hand-written expected values for fields that depend on
// text rules from an earlier file, matching cases by ID.
func Preserve(cases []Case, old *File) int {
	if old == nil {
		return 0
	}
	byID := map[string]Case{}
	for _, c := range old.Cases {
		byID[c.ID] = c
	}
	n := 0
	keep := func(fields, prev []Field) {
		for j, f := range fields {
			if f.Value != Unknown {
				continue
			}
			for _, pf := range prev {
				if pf.Name == f.Name && pf.Value != Unknown {
					fields[j].Value = pf.Value
					n++
				}
			}
		}
	}
	for i := range cases {
		prev, ok := byID[cases[i].ID]
		if !ok {
			continue
		}
		keep(cases[i].Expected, prev.Expected)
		for _, c := range cases[i].Calls {
			for _, pc := range prev.Calls {
				if pc.Target == c.Target {
					keep(c.Fields, pc.Fields)
				}
			}
		}
	}
	return n
}

// Write renders cases.toml to path.
func Write(path string, s *sheet.Sheet, inputOrder []*sheet.Row, refTime time.Time, cs []Case) error {
	return os.WriteFile(path, Format(s, inputOrder, refTime, cs), 0o644)
}

// Format renders cases.toml. Inputs are written in row order, with dates in
// the form their row type expects.
func Format(s *sheet.Sheet, inputOrder []*sheet.Row, refTime time.Time, cs []Case) []byte {
	var b strings.Builder
	fmt.Fprintf(&b, "# Generated by `%s cases` from %s version %d.\n", brand.Command, sheet.FileName, s.Version)
	b.WriteString("# Do not edit, except expected values marked \"?\": those depend on text rules and are kept on regeneration.\n\n")
	fmt.Fprintf(&b, "sheet          = %s\n", quote(s.Slug))
	fmt.Fprintf(&b, "version        = %d\n", s.Version)
	fmt.Fprintf(&b, "reference_time = %s\n", quote(refTime.Format(time.RFC3339)))
	for _, c := range cs {
		b.WriteString("\n[[case]]\n")
		fmt.Fprintf(&b, "id     = %s\n", quote(c.ID))
		covers := make([]string, len(c.Covers))
		for i, k := range c.Covers {
			covers[i] = quote(k)
		}
		fmt.Fprintf(&b, "covers = [%s]\n", strings.Join(covers, ", "))
		var in []string
		for _, r := range inputOrder {
			v, ok := c.Input[r.ID]
			if !ok {
				continue
			}
			in = append(in, r.ID+" = "+inputValue(r, v))
		}
		fmt.Fprintf(&b, "input  = { %s }\n", strings.Join(in, ", "))
		if c.ExpectedReject != "" {
			fmt.Fprintf(&b, "expected_reject = %s\n", quote(c.ExpectedReject))
		} else {
			fmt.Fprintf(&b, "expected = %s\n", inlineTable(c.Expected))
			for _, call := range c.Calls {
				fmt.Fprintf(&b, "expected_calls.%s = %s\n", key(call.Target), inlineTable(call.Fields))
			}
		}
	}
	return []byte(b.String())
}

func inputValue(r *sheet.Row, v any) string {
	if t, ok := v.(time.Time); ok {
		if r.Type == "date" {
			return quote(t.Format("2006-01-02"))
		}
		return quote(t.Format(time.RFC3339))
	}
	return literal(v)
}

// inlineTable nests dotted field names: a.b and a.c become a = { b, c }.
func inlineTable(fields []Field) string {
	type node struct {
		name  string
		value any
		kids  []*node
	}
	root := &node{}
	for _, f := range fields {
		cur := root
		parts := strings.Split(f.Name, ".")
		for i, p := range parts {
			var next *node
			for _, k := range cur.kids {
				if k.name == p {
					next = k
				}
			}
			if next == nil {
				next = &node{name: p}
				cur.kids = append(cur.kids, next)
			}
			if i == len(parts)-1 {
				next.value = f.Value
			}
			cur = next
		}
	}
	var render func(n *node) string
	render = func(n *node) string {
		parts := make([]string, len(n.kids))
		for i, k := range n.kids {
			if len(k.kids) > 0 {
				parts[i] = key(k.name) + " = " + render(k)
			} else {
				parts[i] = key(k.name) + " = " + literal(k.value)
			}
		}
		return "{ " + strings.Join(parts, ", ") + " }"
	}
	return render(root)
}

func literal(v any) string {
	switch x := v.(type) {
	case string:
		return quote(x)
	case bool:
		return strconv.FormatBool(x)
	case float64:
		return sheet.FormatValue(x)
	case time.Time:
		return quote(sheet.FormatValue(x))
	case nil:
		return `""`
	}
	return quote(fmt.Sprint(v))
}

func key(k string) string {
	for _, c := range k {
		if !(c == '_' || c == '-' || c >= 'a' && c <= 'z' || c >= 'A' && c <= 'Z' || c >= '0' && c <= '9') {
			return quote(k)
		}
	}
	return k
}

func quote(s string) string { return strconv.Quote(s) }
