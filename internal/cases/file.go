// File is the content of cases.toml.
type File struct {
	Sheet         string
	Version       int
	ReferenceTime string
	Cases         []Case
}

type fileTOML struct {
	Sheet         string     `toml:"sheet"`
	Version       int        `toml:"version"`
	ReferenceTime string     `toml:"reference_time"`
	Case          []caseTOML `toml:"case"`
}

type caseTOML struct {
	ID             string         `toml:"id"`
	Covers         []string       `toml:"covers"`
	Input          map[string]any `toml:"input"`
	Expected       map[string]any `toml:"expected"`
	ExpectedCalls  map[string]any `toml:"expected_calls"`
	ExpectedReject string         `toml:"expected_reject"`
}

// Read reads and parses cases.toml.
func Read(path string) (*File, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	f, err := ParseFile(data)
	if err != nil {
		return nil, fmt.Errorf("%s: %v", path, err)
	}
	return f, nil
}

// ParseFile parses the content of cases.toml. Expected fields come back
// flattened, in name order; expected calls in stage order.
func ParseFile(data []byte) (*File, error) {
	var ft fileTOML
	if err := toml.Unmarshal(data, &ft); err != nil {
		return nil, err
	}
	f := &File{Sheet: ft.Sheet, Version: ft.Version, ReferenceTime: ft.ReferenceTime}
	for _, c := range ft.Case {
		cs := Case{ID: c.ID, Covers: c.Covers, Input: map[string]any{}, ExpectedReject: c.ExpectedReject}
		for k, v := range c.Input {
			cs.Input[k] = sheet.Normalize(v)
		}
		cs.Expected = sortedFields(c.Expected)
		targets := make([]string, 0, len(c.ExpectedCalls))
		for t := range c.ExpectedCalls {
			targets = append(targets, t)
		}
		sort.Strings(targets)
		for _, t := range targets {
			m, ok := c.ExpectedCalls[t].(map[string]any)
			if !ok {
				return nil, fmt.Errorf("case %q: expected_calls.%s is not a table", c.ID, t)
			}
			cs.Calls = append(cs.Calls, Call{Target: t, Fields: sortedFields(m)})
		}
		f.Cases = append(f.Cases, cs)
	}
	return f, nil
}

func sortedFields(m map[string]any) []Field {
	flat := Flatten(sheet.Normalize(m).(map[string]any))
	names := make([]string, 0, len(flat))
	for k := range flat {
		names = append(names, k)
	}
	sort.Strings(names)
	out := make([]Field, 0, len(names))
	for _, k := range names {
		out = append(out, Field{k, flat[k]})
	}
	return out
}

